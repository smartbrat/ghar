#!/usr/bin/env node
/* Builds dist/brand-theme.css from scripts/brand-palettes.mjs (the per-brand
   role colors) + scripts/brand-theme.roles.css (which surface paints from
   which role). Fails, writing nothing, if any palette misses WCAG contrast.
   Native palettes (the tenant's own chassis design, user-approved) only
   report contrast misses, and roles.css rules written against
   body[data-palette-forced] skip them.

   Usage: npm run build:palettes */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PALETTES } from './brand-palettes.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEX = /^#[0-9a-f]{6}$/i;

const lum = (h) => [1, 3, 5]
  .map((i) => parseInt(h.substr(i, 2), 16) / 255)
  .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  .reduce((a, v, i) => a + v * [0.2126, 0.7152, 0.0722][i], 0);
const ratio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };

const errors = [];
const warnings = [];
let css = '';
for (const [slug, p] of Object.entries(PALETTES)) {
  const dark = p.theme === 'dark';
  const ground = dark ? p.ink : '#ffffff';
  const colors = [...p.primary, ...p.hover, p.text, p.ink, ...p.cta, ...p.ctaHover, p.alt, p.canvas, p.soft];
  for (const c of colors) if (!HEX.test(c)) errors.push(`${slug}: "${c}" is not a 6-digit hex`);
  if (errors.length) continue;

  const need = (label, a, b, min) => { const r = ratio(a, b); if (r < min) (p.native ? warnings : errors).push(`${slug}: ${label} ${a} on ${b} is ${r.toFixed(2)}:1, needs ${min}:1`); };
  need('button text', p.primary[1], p.primary[0], 4.5);
  need('button hover text', p.hover[1], p.hover[0], 4.5);
  need('accent text', p.text, ground, 4.5);
  need('contact CTA text', p.cta[1], p.cta[0], 4.5);
  need('contact CTA hover text', p.ctaHover[1], p.ctaHover[0], 4.5);
  need('contact CTA against card', p.cta[0], p.ink, 3);
  need('card title', '#ffffff', p.ink, 4.5);
  need('chip icon', (p.tokens && p.tokens['--brand-chip']) || p.text, dark ? p.ink : '#ffffff', 3);

  /* Large stat numbers take the alt accent only where it reads (3:1 large text). */
  const stat = !p.native && ratio(p.alt, ground) >= 3 ? p.alt : p.text;

  css += `body[data-palette="${slug}"]{` + [
    `--brand:${p.primary[0]}`, `--brand-on:${p.primary[1]}`,
    `--brand-hover:${p.hover[0]}`, `--brand-hover-on:${p.hover[1]}`,
    `--brand-text:${p.text}`, `--brand-stat:${stat}`, ...(p.noInk ? [] : [`--brand-ink:${p.ink}`]),
    `--brand-cta:${p.cta[0]}`, `--brand-cta-on:${p.cta[1]}`,
    `--brand-cta-hover:${p.ctaHover[0]}`, `--brand-cta-hover-on:${p.ctaHover[1]}`,
    `--brand-alt:${p.alt}`, `--brand-canvas:${p.canvas}`, `--brand-soft:${p.soft}`,
    ...Object.entries(p.tokens || {}).map(([k, v]) => `${k}:${v}`),
  ].join(';') + '}\n';
  const block = (sel, map) => { if (map) css += sel + '{' + Object.entries(map).map(([k, v]) => `${k}:${v}`).join(';') + '}\n'; };
  block(`body[data-palette="${slug}"]:not(.pp-page)`, p.contact);
  block(`body.pp-page[data-palette="${slug}"]`, p.person);
}

if (errors.length) {
  console.error('brand-theme: palette contrast check FAILED, nothing written:\n  ' + errors.join('\n  '));
  process.exit(1);
}

if (warnings.length) console.warn('brand-theme: native palettes below target (tenant design kept):\n  ' + warnings.join('\n  '));

const forced = Object.entries(PALETTES).filter(([, p]) => !p.native).map(([slug]) => `[data-palette="${slug}"]`);
const roles = readFileSync(join(ROOT, 'scripts/brand-theme.roles.css'), 'utf8')
  .replace(/\[data-palette-forced\]/g, `:is(${forced.join(',')})`);
const out = `/* GENERATED by scripts/build-brand-theme.mjs. Do not edit.
   Palettes: scripts/brand-palettes.mjs. Surface mapping: scripts/brand-theme.roles.css. */
${css}
${roles}`;
writeFileSync(join(ROOT, 'dist/brand-theme.css'), out);
console.log(`brand-theme: ${Object.keys(PALETTES).length} palettes, contrast OK, wrote dist/brand-theme.css (${out.length} bytes)`);
